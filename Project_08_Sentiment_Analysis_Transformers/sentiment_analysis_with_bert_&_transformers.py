from transformers import pipeline

# MODEL INITIALIZATION (Transfer Learning)
# We use 'distilbert', a smaller, faster version of BERT perfect for production.
print("Loading Pre-trained Transformer Model...")
sentiment_pipeline = pipeline("sentiment-analysis", model="distilbert-base-uncased-finetuned-sst-2-english")

# DATA INFERENCE (Testing the AI's Brain)
# We test complex sentences where the 'emotion' is subtle.
sentences = [
    "I was skeptical at first, but this product exceeded every expectation!",
    "The service was slow, and frankly, the food was quite bland.",
    "It’s not the best movie I’ve seen, but it’s certainly not the worst."
]

# EXECUTION & ANALYSIS
results = sentiment_pipeline(sentences)
for i, result in enumerate(results):
    print(f"\nSentence: {sentences[i]}")
    print(f"Label: {result['label']} | Confidence: {result['score']:.4f}")

